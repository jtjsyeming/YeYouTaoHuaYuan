    /// <summary>
    /// 月份（1..12）→ 生肖下标（0..11）。
    /// <para><b>按 2026-01 起算</b>：2026-01 = 鼠、2026-11 = 狗、2026-12 = 猪、2027-01 又回到鼠。</para>
    /// </summary>
    /// <remarks>
    /// ⚠ 这是「每月一轮生肖」的<b>虚构主题</b>，<b>与真实农历生肖年无关</b>
    /// （2026 农历是马年，但 2026-01 的主题是鼠）。不写这句，下一个人会想去"修正"它。
    /// </remarks>
    public static int ZodiacIndex(int issue)
    {
        var month = issue / 100 % 100;
        return ((month - 1) % 12 + 12) % 12;      // 月份越界（0/13）也不抛，按回环取
    }

    /// <summary>
    /// 一格的<b>角色</b>（《57》v2.7 §2）。铺盘、渲染、寻路三处共用这一个判据，别再各写一套字符判断。
    /// </summary>
    public enum LlkCellKind
    {
        /// <summary><c>.</c>：空白。没有方块，也不挡路。</summary>
        Empty = 0,

        /// <summary><c>#</c> / <c>+</c>：可消除的脸牌。</summary>
        Face = 1,

        /// <summary><c>o</c>：黑块。不可消、不配对、<b>挡路</b>（Core 里是 <c>-1</c>）。</summary>
        Block = 2,
    }

    /// <summary><paramref name="issue"/> 这一关的第 <paramref name="idx"/> 格是什么。</summary>
    /// <remarks>
    /// 行列换算是本方案<b>最容易写反且最难看出的错</b>：写反后点阵整体转置，格数一模一样
    /// （<c>U16-3</c> 逐格拼比对才抓得住）。越界 <paramref name="idx"/> 返回空位、不抛 ——
    /// 渲染循环里宁可少画一格也不能整页崩。
    /// </remarks>
    public static LlkCellKind CellKind(int issue, int idx)
    {
        if (idx < 0 || idx >= LianliankanCore.CellCount) return LlkCellKind.Empty;

        var ch = ZodiacArt[ZodiacIndex(issue)][idx / LianliankanCore.Cols][idx % LianliankanCore.Cols];
        return ch switch
        {
            'o' => LlkCellKind.Block,
            '.' => LlkCellKind.Empty,
            _ => LlkCellKind.Face,
        };
    }

    /// <summary>
    /// 这一关的可消除方块数（<c>#</c> 与 <c>+</c> 的格数）—— 即 <c>RemainingCount</c> 的初值。
    /// <para><b>现算、不写常量表</b>：《57》v2.7 §2 的 ⚠ 就是这张表手工同步过一次、错了一项（204）。
    /// 代价只是 12 次字符串扫描（每张 320 字符），而它每关只算一两次。</para>
    /// <para>结果一定是偶数 —— 奇数意味着点阵画错了（<c>U16-1</c> 钉住），而铺盘会因此把最后一对拆开。</para>
    /// </summary>
    public static int PlayableCount(int issue)
    {
        var count = 0;
        foreach (var row in ZodiacArt[ZodiacIndex(issue)])
        {
            foreach (var ch in row)
            {
                if (ch == '#' || ch == '+') count++;
            }
        }
        return count;
    }
