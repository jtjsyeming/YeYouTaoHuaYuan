    // 成对闸、分区重排、ForcePair 全部零改动），生肖形状只是一层按 idx 算出来的装饰。
    // 这条边界是本方案的唯一边界：一旦有人让形状影响 cells，成对闸与可解性全都得跟着重算。

    /// <summary>
    /// 12 张生肖点阵（鼠牛虎兔龙蛇马羊猴鸡狗猪），<b>每张 8 行 × 6 列</b>，行序与
    /// <c>LianliankanCore.Rows/Cols</c> 一致（<c>idx = r * 6 + c</c>）。
    /// <para>'#' = 形状格（渲染时叠一层淡主色），'.' = 普通格。<b>不改 cells、不参与成对闸。</b></para>
    /// <para>每行必须恰好 6 个字符、每张必须 8 行、'#' 数在 24~30 之间 —— 三条都由 <c>U16-1</c> 钉死。
    /// 判别力靠"尾/角/耳的位置每张都不同"，不靠"一眼认出是哪个生肖"（8×6 做不到，见《57》§4.2）。</para>
