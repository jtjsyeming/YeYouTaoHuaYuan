    /// <summary>
    /// 月份（1..12）→ 生肖下标（0..11）。
    /// <para><b>按 2026-01 起算</b>：2026-01 = 鼠、2026-11 = 狗、2026-12 = 猪、2027-01 又回到鼠。</para>
    /// </summary>
    /// <remarks>
    /// ⚠ 这是「每月一轮生肖」的<b>虚构主题</b>，<b>与真实农历生肖年无关</b>
    /// （2026 农历是马年，但 2026-01 的主题是鼠）。不写这句，下一个人会想去"修正"它。
    /// </remarks>
    public static int ZodiacIndex(int issue)
    {
        var month = issue / 100 % 100;
        return ((month - 1) % 12 + 12) % 12;      // 月份越界（0/13）也不抛，按回环取
    }

    /// <summary><paramref name="issue"/> 这一关的第 <paramref name="idx"/> 格是否属于当月生肖形状。</summary>
    /// <remarks>
    /// 行列换算 <c>art[idx / 6][idx % 6]</c> 是本方案<b>最容易写反且最难看出的错</b>（<c>U16-3</c> 专门守它）。
    /// 越界 <paramref name="idx"/> 返回 <c>false</c>，不抛 —— 渲染循环里宁可少染一格也不能整页崩。
    /// </remarks>
    public static bool IsZodiacCell(int issue, int idx)
    {
        if (idx < 0 || idx >= 48) return false;
        return ZodiacArt[ZodiacIndex(issue)][idx / 6][idx % 6] == '#';
    }
}
